/// Мгновение, с которого идёт нынешнее воздержание, в миллисекундах эпохи.
///
/// Счёт идёт от последнего мгновения сброса, и таких мгновений ровно два вида:
///
///  * момент последнего срыва, когда срыв в окне обязательства есть
///    (`computed.since#1`). Момента у срыва может не быть — тогда полночь
///    после его дня (`computed.since#2`);
///  * момент обязательства, когда срывов не было вовсе (`computed.since#3`).
///
/// Через серию счёт не ходит, и это главное. Серии посуточны: отметил срыв в
/// половине третьего — сегодня перестало быть чистым днём, серии, накрывающей
/// сегодня, не осталось ни одной, и счётчик, спрашивавший серию, стоял бы на
/// нуле до полуночи. Мгновение того срыва при этом записано и известно, и
/// счёт начинается с него (`computed.since#4`).
///
/// Null — только тогда, когда считать не от чего вовсе: у привычки нет дня
/// обязательства, а значит нет ни окна, в котором ищется срыв, ни второй точки
/// отсчёта (`computed.since#4`).
///
/// [isLapseValue] — судья дня, приходящий швом с поверхности; окно и вход у
/// счётчика те же, что у подписи под ним (см. [lastAbstinenceLapseDay]).
int? abstinenceSinceMillis(
  Habit habit,
  LapseRepository lapses, {
  required bool Function(int storedValue) isLapseValue,
  LocalDate? asOf,
}) {
  final int? committedFrom = habit.definition?.committedFrom;
  if (committedFrom == null) return null;
  final int? lapseDay =
      lastAbstinenceLapseDay(habit, isLapseValue: isLapseValue, asOf: asOf);
  if (lapseDay == null) return _commitmentMillis(habit, committedFrom);
  return _boundaryMillis(
    habit,
    lapses,
    lapseDay: lapseDay,
    cleanEdgeDay: lapseDay + 1,
  );
}

/// День последнего срыва под этим обязательством, или null, когда срывов не
/// было.
///
/// Один вход и один судья на две поверхности: счётчик считает от этого дня, а
/// подпись под ним этот же день называет (`computed.abstinence-screen#2`).
/// Спрашиваются значения дней `habit.computedEntries`, а не журнал срывов:
/// журнал — второй источник того же факта, и на пропуске два входа расходятся
/// — строка в журнале есть, значения дня нет (`computed.day-write#4`). Момент
/// у журнала спрашивается потом и только у найденного дня: журнал — то
/// единственное место, где момент вообще есть.
///
/// Окно начинается днём обязательства: запись старше него в него не входит
/// (`computed.commitment#2`). Кончается оно [asOf] — по умолчанию сегодняшним
/// днём; дальше заглядывать незачем, срыв не лежит позже сегодня.
///
/// Дни спрашиваются с последнего и назад, и первый же срыв есть последний:
/// перебор останавливается на нём. Списком окно не выкладывается — карточка
/// строит его раз в минуту, и у обязательства десятилетней давности это три
/// с половиной тысячи записей на каждую перерисовку, из которых нужна одна.
///
/// [isLapseValue] — та половина судьи, которой у ядра нет: перевод шкалы и
/// ступеньки `Entry` живут на поверхности, и второго такого сравнения в
/// приложении не заводится (`computed.abstinence-cell#2`).
int? lastAbstinenceLapseDay(
  Habit habit, {
  required bool Function(int storedValue) isLapseValue,
  LocalDate? asOf,
}) {
  final int? committedFrom = habit.definition?.committedFrom;
  if (committedFrom == null) return null;
  final int last = (asOf ?? getToday()).daysSince2000;
  for (int day = last; day >= committedFrom; day--) {
    final Entry entry = habit.computedEntries.get(LocalDate(day));
    if (isLapseValue(entry.value)) return day;
  }
  return null;
}

/// Сколько миллисекунд длится [streak].
///
/// Длительность серии есть разница двух мгновений, и правило на обоих концах
/// одно и то же — то, которым [_boundaryMillis] находит границу чистого
/// времени (`computed.since#8`):
///
///  * начало — там, где кончился срыв, лежащий на дне `start - 1`, а у самой
///    первой серии, упирающейся в обязательство, — там, где обязательство
///    было дано (`computed.since#3`);
///  * конец — там, где начался срыв, лежащий на дне `end + 1`;
///  * у идущей серии конца ещё нет, и вместо него берётся «сейчас».
///
/// Кончилась серия или идёт, решает **срыв, который её оборвал**, а не
/// сегодняшнее число: серия кончена тогда, когда день `end + 1` есть срыв
/// (`computed.since#10`). Спросить «конец старше сегодня?» было бы короче и
/// было бы неверно: список серий собирается один раз, а «сегодня» переезжает
/// в полночь, и у открытого экрана идущая серия за одну минуту превращалась
/// бы в завершённую — с концом на вчерашнем дне, на котором срыва нет, — и
/// надпись вставала бы на «N дней 00:00» до следующей перерисовки.
///
/// [isLapseValue] — тот самый судья, которым ячейка списка, клетка календаря,
/// кнопка карточки и подпись под счётчиком судят день по его хранимому
/// значению (`computed.abstinence-cell#2`). Он приходит швом, а не пишется
/// здесь заново: у ядра есть половина этого судьи — `isAbstinenceLapse`, — а
/// вторая половина, перевод шкалы и ступеньки `Entry`, живёт на поверхности,
/// и второго такого сравнения в приложении быть не должно.
///
/// У серии, о концах которой журнал молчит, ответ есть ровно число суток от
/// полуночи до полуночи: часы и минуты нулевые, и это не выдумка, а
/// единственное, что про такую серию известно (`computed.since#2`).
///
/// [nowMillis] — тот же крюк, которым читают текущий момент счётчик
/// воздержания и запись момента срыва (`computed.since#7`): подмена часов в
/// тесте обязана двигать все три числа одним поворотом одного винта.
int abstinenceStreakMillis(
  Habit habit,
  LapseRepository lapses,
  Streak streak, {
  required bool Function(int storedValue) isLapseValue,
  int? nowMillis,
}) {
  final int brokenOn = streak.end.daysSince2000 + 1;
  final bool over =
      isLapseValue(habit.computedEntries.get(LocalDate(brokenOn)).value);
  final int to = over
      ? _boundaryMillis(
          habit,
          lapses,
          lapseDay: brokenOn,
          cleanEdgeDay: brokenOn,
        )
      : nowMillis ?? systemCurrentTimeMillis();
  return to - _startMillis(habit, lapses, streak);
}

/// Мгновение, с которого идёт [streak].
int _startMillis(Habit habit, LapseRepository lapses, Streak streak) =>
    _boundaryMillis(
      habit,
      lapses,
      lapseDay: streak.start.daysSince2000 - 1,
      cleanEdgeDay: streak.start.daysSince2000,
    );

/// Граница чистого времени, упирающаяся в срыв на дне [lapseDay], в
/// миллисекундах эпохи.
///
/// Правило короче, чем кажется, и оно одно на оба конца серии:
///
///  * момент этого срыва известен и больше нуля — считаем от него
///    (`computed.since#1`, `#12`);
///  * момента нет, потому что строка старше миграции 104, приехала из чужой
///    копии или срыв отмечен задним числом (`computed.since#7`), — считаем от
///    полуночи [cleanEdgeDay]: это та граница суток, про которую точно
///    известно, с какой стороны от неё чисто (`computed.since#2`);
///  * срыва там нет вовсе, потому что граница упирается в обязательство, —
///    момент обязательства, а когда его нет, та же полночь
///    (`computed.since#3`).
///
/// Момент срыва, не больший нуля, моментом не считается — тем же доводом,
/// каким чуть ниже `_commitmentMillis` отказывает такому же нулю у
/// обязательства (`computed.since#11`): единственная дверь записи
/// (`AbstinenceSync.setLapse`, `computed.since#7`) кладёт туда либо часы, либо
/// пустоту, и ноль оттуда прийти не может, — но чужая копия базы донесёт что
/// угодно, а счётчик её всё равно спросят. Принятый за настоящий, такой ноль
/// отбросил бы счёт к первому января семидесятого и напечатал бы полвека
/// свободы вместо настоящего числа (`computed.since#12`).
///
/// День срыва читается только тогда, когда он не старше дня обязательства:
/// день обязательства задаёт нижнюю границу окна целиком, в обе стороны, и
/// запись старше него в окно не входит (`computed.commitment#2`). Перенос
/// обязательства вперёд оставляет в журнале срыв, отмеченный до переноса, —
/// его момент по-прежнему лежит в базе, но серия начинается обязательством, а
/// не им, и считать от него значило бы тянуть счёт из-за границы, которую сам
/// человек только что подвинул. На конце серии эта охрана не срабатывает
/// никогда — серия не начинается раньше обязательства, а значит и не
/// кончается раньше, — но второго входа в журнал ради недостижимой ветви не
/// заводится: судья один. Тем же счётом недостижима на конце и ветвь
/// обязательства: `cleanEdgeDay` там есть день после конца серии, а он не
/// бывает днём обязательства.
int _boundaryMillis(
  Habit habit,
  LapseRepository lapses, {
  required int lapseDay,
  required int cleanEdgeDay,
}) {
  final int? id = habit.id;
  final int? committedFrom = habit.definition?.committedFrom;
  if (id != null && (committedFrom == null || lapseDay >= committedFrom)) {
    final int? at = lapses.momentOf(id, lapseDay);
    if (at != null && at > 0) return at;
  }
  if (committedFrom != null && cleanEdgeDay == committedFrom) {
    return _commitmentMillis(habit, committedFrom);
  }
  return _midnightMillis(cleanEdgeDay);
}

/// Мгновение, с которого идёт счёт у обязательства, ни разу не сорванного.
///
/// Момент обязательства, когда он записан, и полночь дня обязательства, когда
/// нет: у привычки, заведённой до миграции 105, и у приехавшей из чужой копии
/// момента не будет вовсе, а полночь его дня — всё, что про такое
/// обязательство известно (`computed.since#3`, `computed.schema#11`).
///
/// Момент, не больший нуля, моментом не считается: ноль есть первое января
/// семидесятого, отрицательное — и того раньше, и обязательства там не давал
/// никто. Принятый за настоящий, он показал бы полвека свободы — та же беда и
/// тот же ответ, что у дня обязательства (`computed.since#11`,
/// `computed.commitment#6`). Отбоя в хранилище при этом не заводится: колонку
/// пишут часы, а не человек, и стеречь там нечего, — а вот напечатать полвека
/// счётчик не вправе.
///
/// Момент, лежащий вне суток [committedFrom], тоже моментом не считается —
/// тем же доводом, только не про ноль, а про день. Редактор пересчитывает
/// момент, когда сохранение назначает день обязательства заново, а не при
/// каждом сохранении, — и стирает его, если перенос уходит назад
/// (`computed.commitment#9`), но эта функция не вправе полагаться на то, что
/// строка обязательно прошла через редактор: у момента срыва ровно та же
/// защита стоит на входе в `_boundaryMillis` — `lapseDay >= committedFrom`, —
/// потому что перенос дня оставляет чужую запись на месте, а не переписывает
/// её сама. Момент обязательства лежит на той же строке, что и день, а не во
/// второй таблице, но опасность та же: строка может прийти с чужой копии,
/// однажды написанная до этой защиты или обойдя её каким-то ещё путём.
/// Принятый за настоящий момент чужого дня, он посчитал бы месячную привычку
/// начатой только что — та же беда, что у буквального нуля, и тот же ответ
/// (`computed.since#13`).
///
/// `at > 0` здесь уже избыточно математически: день обязательства не бывает
/// раньше первого после эпохи (`computed.commitment#6`), а значит его
/// полночь — и вместе с ней [_fallsOnDay] — сама отбрасывает ноль и всё
/// отрицательное, отдельной проверки не спрашивая. Строка тем не менее
/// оставлена: она дешева, не зависит от того, что умеет [_fallsOnDay] сейчас
/// и будет уметь после следующей правки, и называет беду с нулём по имени —
/// той же строкой, какой `_boundaryMillis` называет её у момента срыва, где
/// день сам по себе такой защиты не даёт вовсе.
int _commitmentMillis(Habit habit, int committedFrom) {
  final int? at = habit.definition?.committedAtMillis;
  if (at != null && at > 0 && _fallsOnDay(at, committedFrom)) return at;
  return _midnightMillis(committedFrom);
}

/// Ложится ли мгновение [millis] в сутки дня [day], в зоне человека.
bool _fallsOnDay(int millis, int day) =>
    millis >= _midnightMillis(day) && millis < _midnightMillis(day + 1);

/// Полночь дня [day], в зоне человека, в миллисекундах эпохи.
///
/// И счётчик, и карточка серий показывают длительность, и час её начала
/// должен быть тем же часом, каким человек видит смену суток. `unixTime` —
/// местное время этой полуночи как если бы она была UTC; `utcInstantOfLocal`
/// находит настоящий момент, который на местных часах читается так же.
int _midnightMillis(int day) => utcInstantOfLocal(
      LocalDate(day).unixTime,
      DateUtils.currentTimeZone,
    );
