import '../models/habit.dart';
import '../time/date_utils.dart';
import '../time/local_date.dart';
import 'day_writer.dart';
import 'habit_definition.dart';
import 'lapse_day_value.dart';
import 'lapse_repository.dart';

/// Свод воздержания: журнал срывов → значения дней.
///
/// Ровно та же четвёрка ролей, что у сна («Конвейер» спецификации): источник —
/// палец человека, хранилище — [LapseRepository], определение —
/// [lapseDayValue] с допуском из [HabitDefinition], свод — этот класс.
/// Считает по диапазону, а не по дню: у «дней без срыва» балл дня зависит от
/// прошлого ровно так же, как у свёртки часового пояса во сне.
class AbstinenceSync {
  AbstinenceSync({required this.lapses, required this.writer});

  final LapseRepository lapses;

  /// Единственная дверь записи. Она же — та, что пересчитывает привычку и один
  /// раз объявляет об изменении: в приложении сюда приходит `DayWriter`,
  /// собранный с тем же `onChanged`, что и у сна (`computed.freshness#2`).
  ///
  /// Обязательный параметр без значения по умолчанию — намеренно, той же
  /// причины ради, что и у `SleepSync.writer`: `const DayWriter()` по
  /// умолчанию дал бы собрать свод с молчащей дверью, и он бы скомпилировался,
  /// позеленел в тестах и клал бы дни на диск, пока список показывает
  /// прежнее. Кому нужна тишина — всякому здешнему тесту ядра — тот пишет
  /// `const DayWriter()` сам, и это видно.
  final DayWriter writer;

  /// Записывает или снимает срыв за [date], пересчитывает день и отвечает,
  /// сдвинулось ли значение дня.
  ///
  /// Сегодняшнему срыву дверь ставит и момент — тот, в который его отметили;
  /// срыву, отмеченному задним числом, не ставит (`computed.since#7`). Момент
  /// пишется здесь, а не у жеста: жестов двое — кнопка карточки и клетка
  /// календаря, — и правило, разложенное по ним, доживёт не до всех. Ячейка
  /// списка сюда не заходит вовсе: список — только для просмотра для этого
  /// вида (`computed.abstinence-cell#9`).
  ///
  /// Ответ — свода, а не «дошли до конца»: обе ветки его знают
  /// ([recomputeDays] и [DayWriter.clear]), и он есть тот самый признак, по
  /// которому зовущий решает, перерисовывать ли список. Отвечать `true`
  /// всегда значило бы перерисовывать список и там, где день не изменился —
  /// а значит, не заслуживает перерисовки (`computed.abstinence-cell#5`).
  ///
  /// Идемпотентно: повторный `setLapse(h, d, true)` даёт один срыв — журнал
  /// заменяет строку (`computed.lapses#3`), а [DayWriter] не переписывает
  /// неизменившееся значение (`computed.day-write#5`).
  ///
  /// Снятие идёт не через запись null: `writeDays` на null означает «сказать
  /// нечего» и оставляет запись как была (`computed.day-write#3`). Здесь
  /// сказано другое — «того, что было записано, не было», — и это
  /// [DayWriter.clear] (`computed.day-write#8`).
  bool setLapse(Habit habit, LocalDate date, bool lapsed, {int? amount}) {
    final int id = habit.id!;
    final int day = date.daysSince2000;
    if (lapsed) {
      // Момент есть «сейчас», и правдой он бывает только про сегодняшний день.
      // Срыв, отмеченный задним числом — тап по позавчерашней клетке
      // календаря, — момента не получает: «сейчас» соврало бы о нём на двое
      // суток, а пустота читается как полночь после дня срыва, и вот это про
      // него верно (`computed.since#7`, `computed.since#2`).
      //
      // Часы — `systemCurrentTimeMillis`, те самые, из которых ядро выводит
      // сегодняшний день (`computeToday`), а не `DateTime.now()` напрямую:
      // тест, прибивший часы, прибивает вместе с ними и момент, а ядро,
      // читающее время двумя способами, рано или поздно ответит двумя
      // разными «сейчас».
      final int? at = date == getToday() ? systemCurrentTimeMillis() : null;
      // Величина по умолчанию не повторяется здесь: «один тап есть одна
      // единица» — правило журнала (`computed.lapses#2`), и названная вторым
      // местом, она разъедется с ним при первой же правке.
      if (amount == null) {
        lapses.save(id, day, atMillis: at);
      } else {
        lapses.save(id, day, amount: amount, atMillis: at);
      }
      return recomputeDays(habit, day, day);
    }
    lapses.remove(id, day);
    return writer.clear(habit, day);
  }

  /// Пишет значения дней `[fromDay, toDay]` по строкам журнала.
  ///
  /// Пересчитывает привычку и объявляет об этом ровно тогда, когда значение
  /// дня сдвинулось: второй проход по тому же журналу не пишет ничего, не
  /// пересчитывает ничего и отвечает false (`computed.abstinence-sync#5`).
  ///
  /// **Смена допуска сюда не относится**, хотя и выглядит родственной.
  /// Значение дня есть величина срыва и от допуска не зависит вовсе — от него
  /// зависит только ветвь деления пополам в оценке (`computed.lapse-score#5`).
  /// Значит переоценить уже записанные дни этот метод не может даже в
  /// принципе: [DayWriter] не найдёт здесь ни одного изменившегося дня и
  /// промолчит. Привычку после смены допуска пересчитывает тот, кто допуск и
  /// поменял, — редактор, своим `recompute()` и объявлением рядом с ним.
  ///
  /// Свод добавляет и меняет значения, но не снимает их: день, под которым
  /// строки журнала нет, остаётся с тем, что в нём лежит
  /// (`computed.abstinence-sync#3`). По диапазону свод не властен, и это
  /// намеренно: снятие есть отдельное высказывание — «того, что было
  /// записано, не было», — и оно идёт через `setLapse(..., false)` и
  /// [DayWriter.clear] (`computed.day-write#8`), где на один день приходится
  /// одно объявление.
  bool recomputeDays(Habit habit, int fromDay, int toDay) {
    // Перевёрнутый диапазон — вопрос ни о чём. Пустой цикл ответил бы на него
    // тем же false, но сперва сходил бы за этим в базу.
    if (toDay < fromDay) return false;
    final int id = habit.id!;
    final Map<int, int> journal = lapses.range(id, fromDay, toDay);
    final Map<int, int?> values = <int, int?>{};
    for (int day = fromDay; day <= toDay; day++) {
      values[day] = lapseDayValue(journal[day] ?? 0);
    }
    return writer.writeDays(habit, values);
  }

  /// Весь диапазон обязательства — от `committedFrom` до сегодня.
  ///
  /// Нет дня обязательства — нет и обязательства, которое можно пройти:
  /// подставленный вместо него ноль накрыл бы двадцать шесть лет до эпохи
  /// (`computed.commitment#6`).
  ///
  /// Определение приходит параметром, а не берётся у `habit.definition`,
  /// потому что зовущий держит в руках **новое** определение — то, которое он
  /// только что сохранил и ещё не прикрепил к живой привычке.
  bool recomputeAll(Habit habit, HabitDefinition definition) {
    final int? from = definition.committedFrom;
    if (from == null) return false;
    return recomputeDays(habit, from, getToday().daysSince2000);
  }
}
