/// Спрашивает величину дня и отдаёт её в целых единицах привычки, или null,
/// когда ответа не было.
///
/// Свой маршрут, а не общая дверь числа. `showNumberPopup` — и в списке, и на
/// экране привычки — закрыт охраной вычисляемых привычек
/// (`computed.write-paths#3`), и открывать его ради воздержания значило бы
/// снять запрет со всех: человек начал бы писать вычисленное значение дня
/// руками, а следующий пересчёт молча его затирал бы. Здесь пишется не
/// значение дня, а величина в журнал; значение дня из неё считает приложение
/// (`computed.lapse-score#2`).
///
/// Виджет тот же самый — портированный [NumberDialog], со своими надписями и
/// своей клавиатурой. Новых строк локализации ввод не приносит.
///
/// [initialAmount] — то, что в дне уже записано, в целых единицах, и ноль,
/// когда не записано ничего. Вопрос есть правка, а не запись поверх вслепую:
/// тап доходит сюда только на дне, который **не** срыв, а при допуске
/// тридцать таким днём бывает и день с записанными двадцатью минутами. Открой
/// его нулём — и человек подтвердил бы «сорок пять», не увидев, что стирает
/// свои двадцать (`computed.abstinence-cell#8`).
///
/// [prompt] — обещание, против которого вводят число: «Не более 30 минут в
/// день». Собирает его [abstinenceAmountPrompt], и приходит оно готовой
/// строкой.
///
/// Определение сюда по-прежнему не едет, и это решение, а не упущение.
/// Спросить у него можно было бы ровно одно — допуск, — и класть допуск в
/// поле нельзя: предзаполненные «30» человек подтвердил бы не глядя, и
/// получилась бы величина, которая обещание **держит**, в ответ на «я
/// сорвался». Отсутствие параметра держит это лучше комментария: подставить
/// туда допуск не из чего, даже по ошибке. Величина дня приходит числом,
/// обещание — строкой, и ни то ни другое допуском стать не может.
Future<int?> askLapseAmount(
  BuildContext context, {
  required int initialAmount,
  required String prompt,
  required core.Preferences preferences,
  required core.Color color,
}) async {
  // Тот же слот, что у портированного попапа числа (`number-dialog.popup#18`,
  // `platform-glue.transient-ui-helpers#4`, `#5`). Без него этот вход был бы
  // единственным в файле, который в слот не встаёт: `EntryPanel.onTap` на
  // время ожидания не заперт, и второй тап положил бы второй диалог поверх
  // первого, а `onPause` экрана оставил бы открытый вопрос висеть.
  final NumberDialogResult? result =
      await dismissCurrentAndShow<NumberDialogResult>(
    context,
    () => showNumberDialog(
      context,
      // Незаполненная запись открывается нулём (`number-dialog.popup#4`),
      // заполненная — тем, что в ней записано.
      value: initialAmount.toDouble(),
      notes: '',
      prompt: prompt,
      // Поля заметок здесь нет: в `Lapses` нет столбца под них, а поле,
      // которое принимает текст и молча его теряет, хуже отсутствующего
      // (`audit7.numeric-entry-popup-throws-away-a#1`). Провести заметку
      // насквозь — это миграция схемы, а не аргумент диалога.
      showNotes: false,
      // NumberDialog красит только кнопки булевого ряда, которого здесь нет;
      // цвет передаётся тем же, каким его передаёт портированный попап числа
      // (`number-dialog.popup#1`).
      color: color,
      preferences: preferences,
    ),
  );
  if (result == null) return null;

  // Журнал хранит целые единицы, и меньше одной он не хранит вовсе
  // (`computed.lapses#2`): ноль удовлетворяет «не больше допуска» при любом
  // допуске, то есть означает «ничего не было», а это молчание — отсутствие
  // строки, а не строка с нулём. Ответ «ноль» поэтому равен отказу.
  final int amount = result.value.round();
  return amount < core.LapseRepository.minimumAmount ? null : amount;
}

/// Что попап говорит над полем: обещание, против которого вводят число.
///
/// Допуск и единица лежат рядом в полезной нагрузке (`computed.allowance#2`),
/// и порознь ни один из них на вопрос не отвечает: «сколько?» без «чего и из
/// скольких» — вопрос, на который нечем ответить.
///
/// Единица есть слово самого человека, введённое в форме свободным текстом, и
/// вставляется как есть: согласовать её с числом невозможно — «30 минуты» так
/// и останется, если он написал «минуты», — но это ровно то, что уже делает
/// числовая ячейка списка со своей единицей. `count` — не слово, а признак
/// «единицу оставили пустой», и показывать его нельзя: «Не более 3 count в
/// день» было бы мусором.
///
/// Число форматируется тем же [NumberDialog.formatValue], каким попап
/// заполняет поле, чтобы «30» над полем и «30» в поле были одним числом,
/// написанным одинаково.
String abstinenceAmountPrompt(L10n l10n, core.HabitDefinition definition) {
  final String allowance =
      NumberDialog.formatValue(core.abstinenceAllowanceOf(definition));
  final String unit = core.abstinenceUnitOf(definition);
  return unit == core.abstinenceUnitCount
      ? l10n.abstinenceAmountPromptNoUnit(allowance)
      : l10n.abstinenceAmountPrompt(allowance, unit);
}
